-- 2) Historial de movimientos de inventario (kardex)
create table if not exists public.movimientos_inv (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  fecha       text,
  hora        text,
  usuario     text,
  inv_id      bigint,
  ref         text,
  talla       numeric,
  delta       integer not null,
  stock_final integer,
  motivo      text
);
create index if not exists movimientos_inv_inv_id on public.movimientos_inv (inv_id);

-- 3) Tareas diarias (si no existe)
create table if not exists public.tareas (
  id      bigint generated by default as identity primary key,
  fecha   text,
  usuario text,
  tarea   text,
  hora    text
);

-- 4) Permisos: solo el equipo con sesión (igual que seguridad.sql)
do $$
declare t text;
begin
  foreach t in array array['movimientos_inv','tareas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "equipo con sesion" on public.%I', t);
    execute format('create policy "equipo con sesion" on public.%I for all to authenticated using (true) with check (true)', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;

-- 5) Inventario: nunca cantidades negativas (protección extra en la base de datos)
--    Si falla porque ya hay alguna cantidad negativa, corrígela en Inventario y vuelve a ejecutar.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'inventario_cant_no_negativa') then
    alter table public.inventario add constraint inventario_cant_no_negativa check (cant >= 0);
  end if;
end $$;

-- Recargar el esquema para que la app vea los cambios de inmediato
notify pgrst, 'reload schema';
